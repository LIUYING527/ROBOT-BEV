"""我们的语义任务词表 + VLM 输出 → 语义任务 + 语义任务 → 学长 4 模式桥接。

背景: 我们架构的 VLM 慢脑输出【语义场景/任务】(区别于学长的 4 运动基元)。
但要【尽快跑通完整链路】, 当前快脑仍是学长 ckpt(只认 cruise/turn/inspect/exit 4 模式槽)。
故此处提供【临时桥接】: 语义任务 -> 最接近的 4 模式, 让两个脑先真正串起来端到端跑。

⚠️这是过渡件。最终架构 = VLM 语义任务条件经新注入通路进【重训后】的快脑(见
docs/下一步_仿真优化与模型搭建_0703.md 的 B3/B5), 那时不再走这个 4 模式桥。
"""

# ---- 我们的语义任务集(B2, 从慢脑验证收敛; 离散语义集起步方案) ----
SEM_TASKS = [
    "直行巡航",        # 走廊直行, 无目标
    "靠近设备巡检",    # 阀门/配电柜/管道/水泵等设备
    "岔路选向",        # 岔路口/转弯
    "接近出口",        # 走廊尽头/门/安全出口
    "降质暂停",        # 画面全黑/严重糊/故障 -> 停等
]

# ---- 语义任务 -> 学长 ckpt 的 4 模式(临时桥接) ----
SEM_TO_CKPT_MODE = {
    "直行巡航": "cruise",
    "靠近设备巡检": "inspect",
    "岔路选向": "turn",
    "接近出口": "exit",
    "降质暂停": "cruise",   # ckpt 无"停"模式, 暂映射 cruise(靠速度 clamp 保守)
}

# ---- 关键词 -> 语义任务(按优先级顺序匹配 VLM 的自由文本) ----
# 顺序重要: 先判降质/出口, 再判岔路, 再判设备巡检, 最后兜底巡航。
_RULES = [
    (["暂停", "等待", "恢复", "全黑", "故障", "无信号", "模糊不清"], "降质暂停"),
    (["出口", "安全出口", "尽头", "门口", "退出"], "接近出口"),
    (["岔", "路口", "转弯", "选向", "分叉", "拐"], "岔路选向"),
    (["阀门", "配电柜", "设备", "管道", "水泵", "仪表", "巡检", "查看", "靠近"], "靠近设备巡检"),
]


def classify_task(text):
    """VLM 的自由任务文本 -> 我们的语义任务(SEM_TASKS 之一)。兜底=直行巡航。"""
    t = text or ""
    for kws, sem in _RULES:
        if any(k in t for k in kws):
            return sem
    return "直行巡航"


def sem_to_ckpt_mode(sem_task):
    """语义任务 -> 学长 ckpt 4 模式(临时桥)。"""
    return SEM_TO_CKPT_MODE.get(sem_task, "cruise")


def vlm_text_to_ckpt_mode(text):
    """一步到位: VLM 自由文本 -> (语义任务, 学长 4 模式)。"""
    sem = classify_task(text)
    return sem, sem_to_ckpt_mode(sem)
